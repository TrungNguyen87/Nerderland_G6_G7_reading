/* =====================================================================
   Werkwoordtrainer - de werkwoorden.
   js/dictee.js maakt hier eindeloos nieuwe d/t/dt-opdrachten van.

   Elke vorm staat er voluit in, zodat de trainer nooit zelf een vorm
   hoeft te bedenken:
     inf    het hele werkwoord            stem  de ik-vorm
     past   verleden tijd enkelvoud       pp    voltooid deelwoord
     pastPl verleden tijd meervoud (alleen nodig als het niet past + n is)
     aux    'h' (heeft) of 'z' (is)       lv    1 = groep 6, 2 = groep 7, 3 = groep 8
     en     Engelse betekenis (voor de hint in het Engels)
     c      aanvullingen die na het werkwoord kunnen staan: { nl, en }.
            Ze moeten passen bij ik, jij, u, hij, zij en wij, in de
            tegenwoordige tijd, de verleden tijd en de voltooide tijd.
            Een aanvulling met eigen `subj` hoort alleen bij die
            onderwerpen.
     subj   vaste onderwerpen (het, het vliegtuig...): dan alleen hij-vormen
     pre    voorvoegsel (be, ge, ver, ont, her): geen extra ge-
     sp/spp sterke verleden tijd / sterk voltooid deelwoord
     bad    { past: [...], pp: [...] }: foute vormen voor de sterke vormen
     t      's' = een toestand (wonen, houden van): in de verleden tijd
            "toen" of "vroeger" in plaats van "gisteren"
     noIk   geen ik-vorm vragen (ik houd en ik hou zijn allebei goed)

   tools/validate.js controleert de vormen (stam + t, 't kofschip,
   ge- ervoor of niet) en tools/smoke.mjs speelt er rondes mee.
   ===================================================================== */

